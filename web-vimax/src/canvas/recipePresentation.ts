export function recipeSlotLabel(key: string): string {
  const normalized = String(key || '').trim();
  if (!normalized) return '配方参数';
  const direct = DIRECT_LABELS[normalized];
  if (direct) return direct;
  const translated = normalized
    .split('_')
    .map((token) => TOKEN_LABELS[token] || '')
    .filter(Boolean)
    .join('·');
  return translated || '配方参数';
}

